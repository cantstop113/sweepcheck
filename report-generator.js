// report-generator.js — SweepCheck "Generate My Report" feature.
//
// Entirely client-side: no backend, no network calls beyond what index.html's
// checker already made. Reads the in-memory result object that index.html's
// existing checkWallet()/checkToken() calls build (exposed as
// window.sweepCheckResult after a check finishes — see index.html), fills in
// two of the templates/ report drafts with that data, and offers them as
// downloads. Anything this tool doesn't know (victim's name, narrative,
// transaction hashes it never looked up, etc.) is left as a clearly marked
// "[FILL IN: ...]" blank — never guessed.
//
// This file does not touch or duplicate the check logic in index.html; it
// only reads the result object that logic already produces.

(function () {
  "use strict";

  const CHAIN_NAMES = {
    bsc: "BNB Chain",
    base: "Base",
    optimism: "Optimism",
    ethereum: "Ethereum",
  };

  function chainName(key) {
    return CHAIN_NAMES[key] || key;
  }

  function fillIn(label) {
    return "[FILL IN: " + label + "]";
  }

  function fmtDateUTC(iso) {
    try {
      return new Date(iso).toISOString().replace("T", " ").slice(0, 16) + " UTC";
    } catch {
      return fillIn("date");
    }
  }

  // --- Evidence log (templates/01-evidence-log.md) -------------------------

  const EVIDENCE_LOG_TEMPLATE = `# 1. Evidence log

Fill this in first. Every report, email, and dispute uses the same facts, so writing them down once keeps your story consistent and saves you retyping.

**Where to find each item:** open your wallet address on the block explorer (bscscan.com, basescan.org, etherscan.io). Click a transaction to see its hash (the long ID at the top), date, sender, and receiver.

## Your wallets

| Wallet address | Network(s) | Still holds | Status |
|---|---|---|---|
__WALLET_ROWS__

## New safe wallet

| Address | Created on | Created how |
|---|---|---|
| __NEW_WALLET__ | __NEW_WALLET_DATE__ | __NEW_WALLET_HOW__ |

## Transactions you did NOT make

| Date and time (UTC) | Network | What happened | Amount | From | To | Transaction hash | Evidence level |
|---|---|---|---|---|---|---|---|
__TX_ROWS__

## Attacker addresses

| Address | What it did | First seen (hash) | Funded by (from explorer "Funded By") |
|---|---|---|---|
__ATTACKER_ROWS__

## Timeline

| Date | What happened | Source |
|---|---|---|
__TIMELINE_ROWS__

## Contacts and reports

| Date | Who | How | Reference / ticket # | Reply | Next follow-up |
|---|---|---|---|---|---|
| __CONTACT_DATE__ | __CONTACT_WHO__ | __CONTACT_HOW__ | __CONTACT_REF__ | __CONTACT_REPLY__ | __CONTACT_NEXT__ |

## Losses

- **Confirmed lost (transferred out, with hashes):** __CONFIRMED_LOST__
- **Stuck but still in the wallet:** __STUCK__
- **Not sure:** __NOT_SURE__

---
*Generated by SweepCheck's "Generate My Report" feature on __GENERATED_AT__ from a live, read-only check of __ADDRESS__ on __CHAINS__. Fields marked [FILL IN: ...] are things this tool cannot know and must be filled in by hand.*
`;

  function buildEvidenceLog(result) {
    const { address, checkedAt, chainsChecked, walletResults, tokenResult } = result;
    const chainLabels = (chainsChecked || []).map(chainName).join(", ");

    // --- Your wallets: one row, balances/status rolled up across chains ---
    const perChainBalance = walletResults
      .map((r) => `${r.nativeBalance} ${CHAIN_NAMES[r.chain] ? (r.chain === "bsc" ? "BNB" : "ETH") : "?"} (${chainName(r.chain)})`)
      .join("; ");
    let status = "safe";
    const anySweeper = walletResults.some((r) => r.delegate && (r.delegate.kind === "sweeper" || r.delegate.kind === "suspicious"));
    const anyBlacklisted = tokenResult && tokenResult.blacklisted === true;
    if (anySweeper) status = "swept (sweeper or stolen-key sign found live — see findings)";
    else if (anyBlacklisted) status = "frozen (token blacklist found live)";
    else status = "no sweeper found live (can't prove the key itself is safe)";
    const walletRow = `| ${address} | ${chainLabels} | ${perChainBalance || fillIn("amounts and tokens")} | ${status} |`;

    // --- Transactions you did NOT make: SweepCheck doesn't scan tx history ---
    let txRows;
    if (anySweeper) {
      const sweeperChains = walletResults.filter((r) => r.delegate && (r.delegate.kind === "sweeper" || r.delegate.kind === "suspicious"));
      txRows = sweeperChains
        .map((r) => {
          const what = "EIP-7702 sweeper delegation attached"
            + (r.delegate.forwardsTo ? " — forwards incoming coins (destination listed under Attacker addresses)" : "");
          return `| ${fillIn("date/time of the set-code tx, from explorer")} | ${chainName(r.chain)} | ${what} | n/a (delegation, not a transfer) | ${address} | ${r.delegate.address} | ${fillIn("set-code transaction hash from explorer")} | unconfirmed |`;
        })
        .join("\n");
    } else {
      txRows = `| ${fillIn("date")} | ${fillIn("network")} | ${fillIn("what happened")} | ${fillIn("amount")} | ${fillIn("from")} | ${fillIn("to")} | ${fillIn("transaction hash")} | ${fillIn("verified / unconfirmed")} |`;
    }

    // --- Attacker addresses ---
    let attackerRows = [];
    for (const r of walletResults) {
      if (r.delegate && (r.delegate.kind === "sweeper" || r.delegate.kind === "suspicious")) {
        attackerRows.push(
          `| ${r.delegate.address} | ${r.delegate.label || "sweeper/delegate contract attached to wallet (" + chainName(r.chain) + ")"} | ${fillIn("first-seen hash from explorer")} | ${fillIn("Funded By, from explorer")} |`
        );
        if (r.delegate.forwardsTo) {
          attackerRows.push(
            `| ${r.delegate.forwardsTo} | received stolen coins (forwarding destination on ${chainName(r.chain)}) | ${fillIn("first-seen hash from explorer")} | ${fillIn("Funded By, from explorer")} |`
          );
        }
      }
    }
    if (tokenResult) {
      for (const a of tokenResult.allowances || []) {
        if (/attacker/i.test(a.label || "")) {
          attackerRows.push(`| ${a.spender} | got token approval (${a.amount} ${tokenResult.symbol}) | ${fillIn("first-seen hash from explorer")} | ${fillIn("Funded By, from explorer")} |`);
        }
      }
    }
    if (!attackerRows.length) {
      attackerRows.push(`| ${fillIn("address")} | ${fillIn("what it did")} | ${fillIn("first-seen hash")} | ${fillIn("funded by")} |`);
    }

    // --- Timeline: one factual row from this run ---
    const summary = anySweeper
      ? "sweeper / stolen-key sign found"
      : anyBlacklisted
      ? "token blacklist found"
      : "no sweeper found on networks checked";
    const timelineRows = `| ${fmtDateUTC(checkedAt)} | Ran SweepCheck automated check on ${chainLabels} — result: ${summary} | SweepCheck tool (automated, read-only) |`;

    // --- Losses ---
    const stuckParts = [];
    for (const r of walletResults) {
      const n = parseFloat((r.nativeBalance || "0").replace(/,/g, ""));
      if (n > 0) stuckParts.push(`${r.nativeBalance} ${r.chain === "bsc" ? "BNB" : "ETH"} on ${chainName(r.chain)}`);
    }
    if (tokenResult && tokenResult.balance && tokenResult.balance !== "unknown" && parseFloat(tokenResult.balance.replace(/,/g, "")) > 0) {
      stuckParts.push(`${tokenResult.balance} ${tokenResult.symbol}${tokenResult.blacklisted ? " (blacklisted — can't move until the token team lifts it)" : ""}`);
    }
    const stuck = stuckParts.length ? stuckParts.join("; ") : fillIn("tokens and amounts still in the wallet, if any");

    return EVIDENCE_LOG_TEMPLATE
      .replace("__WALLET_ROWS__", walletRow)
      .replace("__NEW_WALLET__", fillIn("0x... new wallet address"))
      .replace("__NEW_WALLET_DATE__", fillIn("date"))
      .replace("__NEW_WALLET_HOW__", fillIn("new phrase, new device / hardware wallet"))
      .replace("__TX_ROWS__", txRows)
      .replace("__ATTACKER_ROWS__", attackerRows.join("\n"))
      .replace("__TIMELINE_ROWS__", timelineRows)
      .replace("__CONTACT_DATE__", fillIn("date"))
      .replace("__CONTACT_WHO__", fillIn("IC3 / wallet support / project team"))
      .replace("__CONTACT_HOW__", fillIn("form / email / chat"))
      .replace("__CONTACT_REF__", fillIn("number"))
      .replace("__CONTACT_REPLY__", fillIn("summary"))
      .replace("__CONTACT_NEXT__", fillIn("date"))
      .replace("__CONFIRMED_LOST__", fillIn("amount, with transaction hashes — SweepCheck does not scan transaction history"))
      .replace("__STUCK__", stuck)
      .replace("__NOT_SURE__", fillIn("anything unconfirmed"))
      .replace("__GENERATED_AT__", fmtDateUTC(checkedAt))
      .replace("__ADDRESS__", address)
      .replace("__CHAINS__", chainLabels);
  }

  // --- IC3 report (templates/02-ic3-report.md) ------------------------------

  const IC3_TEMPLATE = `# 2. FBI IC3 report

**Where:** [ic3.gov](https://www.ic3.gov/) → File a Complaint. US residents, or crimes involving US companies.
**File this first.** Save the confirmation number and the PDF copy it offers at the end; you can't get the PDF later.

## Section by section

**Victim information:** __VICTIM_INFO__

**Financial transactions:** add one entry per stolen transaction from your [evidence log](01-evidence-log.md):
- Type: *cryptocurrency*
- Amount and date
- Sending address (yours) and receiving address (the attacker's)
- Transaction hash

**Subject (the attacker):** you usually don't have a name. Enter attacker wallet addresses and any website, app, or username involved.

**Description:** paste and fill this in:

> I own the wallet(s) __ADDRESSES__ on __NETWORKS__. Unknown attackers obtained my wallet key(s). Starting around __START_DATE__, __WHAT_HAPPENED__. I did not make any outgoing transactions after __LAST_KNOWN_GOOD_DATE__.
>
> **How it may have happened:** __HOW_IT_HAPPENED__.
>
> **Attacker addresses:**
__ATTACKER_LINES__
>
> **Lead for investigators:** __LEAD__
>
> **Confirmed loss:** __CONFIRMED_LOSS__.
> **Additionally inaccessible:** __INACCESSIBLE__.
>
> I have an evidence log with all addresses and transaction hashes and can provide it on request.

## Tips
- **Only list confirmed losses as losses.** Put stuck tokens under "inaccessible."
- No hash, no claim. If you aren't sure about something, write *unconfirmed*.
- IC3 rarely replies. That's normal. Its number is what other reports and exchanges ask for.

---
*Generated by SweepCheck's "Generate My Report" feature on __GENERATED_AT__ from a live, read-only check of __ADDRESS__ on __CHAINS__. Fields marked [FILL IN: ...] are things this tool cannot know and must be filled in by hand before filing.*
`;

  function buildIC3Report(result) {
    const { address, checkedAt, chainsChecked, walletResults } = result;
    const chainLabels = (chainsChecked || []).map(chainName).join(", ");
    const anySweeper = walletResults.some((r) => r.delegate && (r.delegate.kind === "sweeper" || r.delegate.kind === "suspicious"));

    const whatHappened = anySweeper
      ? "a sweeper was attached that redirects anything sent to the wallet"
      : fillIn("describe what happened: funds transferred out / a sweeper was attached / other");

    const attackerLines = [];
    for (const r of walletResults) {
      if (r.delegate && (r.delegate.kind === "sweeper" || r.delegate.kind === "suspicious")) {
        attackerLines.push(`> - ${r.delegate.address}: ${r.delegate.label || "sweeper/delegate contract attached on " + chainName(r.chain)}, transaction ${fillIn("hash from explorer")}`);
        if (r.delegate.forwardsTo) {
          attackerLines.push(`> - ${r.delegate.forwardsTo}: received forwarded stolen coins on ${chainName(r.chain)}, transaction ${fillIn("hash from explorer")}`);
        }
      }
    }
    if (!attackerLines.length) {
      attackerLines.push(`> - ${fillIn("address")}: ${fillIn("what it did")}, transaction ${fillIn("hash")}`);
    }

    return IC3_TEMPLATE
      .replace("__VICTIM_INFO__", fillIn("your real name and contact details"))
      .replace("__ADDRESSES__", address)
      .replace("__NETWORKS__", chainLabels)
      .replace("__START_DATE__", fillIn("date you first noticed"))
      .replace("__WHAT_HAPPENED__", whatHappened)
      .replace("__LAST_KNOWN_GOOD_DATE__", fillIn("date of your last legitimate transaction"))
      .replace("__HOW_IT_HAPPENED__", fillIn("e.g., a fake support contact, a website I connected to, a download, unknown — say \"unknown\" if you don't know"))
      .replace("__ATTACKER_LINES__", attackerLines.join("\n"))
      .replace(
        "__LEAD__",
        anySweeper
          ? `attacker address ${fillIn("address")} was first funded on ${fillIn("date")} by ${fillIn("exchange name")} in transaction ${fillIn("hash")}. Exchanges verify identity, so I ask that investigators request the account holder's information for that withdrawal.`
          : fillIn("any lead for investigators, if known")
      )
      .replace("__CONFIRMED_LOSS__", fillIn("amount, transactions (hashes) — SweepCheck does not scan transaction history"))
      .replace("__INACCESSIBLE__", fillIn("tokens still in the compromised wallet, approximate value, and why (frozen / swept)"))
      .replace("__GENERATED_AT__", fmtDateUTC(checkedAt))
      .replace("__ADDRESS__", address)
      .replace("__CHAINS__", chainLabels);
  }

  // --- Download helper -------------------------------------------------------

  function downloadText(filename, text) {
    const blob = new Blob([text], { type: "text/markdown;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    setTimeout(() => URL.revokeObjectURL(url), 2000);
  }

  function safeAddrForFilename(addr) {
    return (addr || "wallet").replace(/[^0-9a-zA-Z]/g, "").slice(0, 10) || "wallet";
  }

  function generateReports() {
    const result = window.sweepCheckResult;
    if (!result || !result.walletResults || !result.walletResults.length) {
      alert("Run a check first — there's nothing to put in a report yet.");
      return;
    }
    const tag = safeAddrForFilename(result.address);
    downloadText(`sweepcheck-evidence-log-${tag}.md`, buildEvidenceLog(result));
    downloadText(`sweepcheck-ic3-report-draft-${tag}.md`, buildIC3Report(result));
  }

  function wire() {
    const btn = document.getElementById("generate-report-btn");
    if (!btn) return;
    btn.addEventListener("click", generateReports);
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", wire);
  } else {
    wire();
  }

  // Exposed for the one-off local test script (not used by the page itself).
  if (typeof module !== "undefined" && module.exports) {
    module.exports = { buildEvidenceLog, buildIC3Report };
  }
})();
